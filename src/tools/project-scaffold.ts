function generateReadme(
  projectName: string,
  buildSystem: BuildSystem,
  cppStandard: CppStandard,
  testFramework: TestFramework,
): string {
  const lines: string[] = [
    `# ${projectName}`,
    "",
    `Modern C++${cppStandard} project bootstrapped with [cpp-mcp](https://github.com/CHOCEK-RB/cpp-mcp).`,
    "",
    "## Quick Start",
    "",
  ];

  if (buildSystem === "xmake") {
    lines.push("### Build with Xmake", "```bash", "xmake", "xmake run", "```", "");
    if (testFramework !== "none") {
      lines.push("### Run Tests", "```bash", "xmake test", "```", "");
    }
    lines.push(
      "### Generate compile_commands.json for clangd",
      "```bash",
      "xmake project -k compile_commands",
      "```",
    );
  } else {
    lines.push(
      "### Build with CMake",
      "```bash",
      "cmake -B build -DCMAKE_EXPORT_COMPILE_COMMANDS=ON",
      "cmake --build build",
      "```",
      "",
    );
    if (testFramework !== "none") {
      lines.push(
        "### Run Tests",
        "```bash",
        "ctest --test-dir build --output-on-failure",
        "```",
        "",
      );
    }
    lines.push("### Setup clangd LSP", "```bash", "ln -sf build/compile_commands.json .", "```");
  }

  lines.push("");
  return lines.join("\n");
}

export async function scaffoldProject(
  options: ScaffoldProjectOptions,
): Promise<ScaffoldProjectResult> {
  const {
    projectName,
    targetDir: rawTargetDir,
    buildSystem = "xmake",
    projectType = "executable",
    cppStandard: rawCppStandard,
    testFramework = "catch2",
    packageManager = buildSystem === "xmake" ? "xrepo" : "none",
    initClangTools = true,
    initGit = false,
    dryRun = false,
    overwrite = false,
  } = options;

  // No explicit flag or CPP_MCP_STD: fall back to the project policy, then "20".
  const { policy } = await loadProjectPolicy(process.cwd());
  const cppStandard = (resolveStandard({ flag: rawCppStandard, policy }) ?? "20") as CppStandard;

  if (!VALID_BUILD_SYSTEMS.has(buildSystem)) {
    throw new Error(
      `Invalid build system '${buildSystem}'. Supported: ${Array.from(VALID_BUILD_SYSTEMS).join(", ")}.`,
    );
  }
  if (!VALID_PROJECT_TYPES.has(projectType)) {
    throw new Error(
      `Invalid project type '${projectType}'. Supported: ${Array.from(VALID_PROJECT_TYPES).join(", ")}.`,
    );
  }
  if (!VALID_CPP_STANDARDS.has(cppStandard)) {
    throw new Error(
      `Invalid C++ standard '${cppStandard}'. Supported: ${Array.from(VALID_CPP_STANDARDS).join(", ")}.`,
    );
  }
  if (!VALID_TEST_FRAMEWORKS.has(testFramework)) {
    throw new Error(
      `Invalid test framework '${testFramework}'. Supported: ${Array.from(VALID_TEST_FRAMEWORKS).join(", ")}.`,
    );
  }
  if (!VALID_PACKAGE_MANAGERS.has(packageManager)) {
    throw new Error(
      `Invalid package manager '${packageManager}'. Supported: ${Array.from(VALID_PACKAGE_MANAGERS).join(", ")}.`,
    );
  }

  if (!projectName?.trim()) {
    throw new Error("Project name cannot be empty.");
  }

  const trimmedName = projectName.trim();
  if (!/^[a-zA-Z0-9_\-.]+$/.test(trimmedName)) {
    throw new Error(
      `Invalid project name '${trimmedName}'. Project names may only contain alphanumeric characters, underscores, hyphens, and dots.`,
    );
  }

  const identifier = sanitizeIdentifier(trimmedName);
  const targetDir = rawTargetDir
    ? path.resolve(rawTargetDir)
    : path.resolve(process.cwd(), trimmedName);

  // Validate directory state if writing to disk
  if (!dryRun && existsSync(targetDir)) {
    const existingEntries = await fs.readdir(targetDir);
    if (existingEntries.length > 0 && !overwrite) {
      throw new Error(
        `Directory '${targetDir}' already exists and contains ${existingEntries.length} file(s). Use 'overwrite: true' (or '--force') to proceed.`,
      );
    }
  }

  const files: Record<string, string> = {};

  // 1. Build configuration
  if (buildSystem === "xmake") {
    files["xmake.lua"] = generateXmakeConfig(
      trimmedName,
      identifier,
      projectType,
      cppStandard,
      testFramework,
      packageManager,
    );
  } else {
    files["CMakeLists.txt"] = generateCMakeConfig(
      trimmedName,
      identifier,
      projectType,
      cppStandard,
      testFramework,
      packageManager,
    );
  }

  // 2. Package manager manifest if applicable
  if (packageManager === "vcpkg") {
    files["vcpkg.json"] = JSON.stringify(
      {
        $schema:
          "https://raw.githubusercontent.com/microsoft/vcpkg-tool/main/docs/vcpkg.schema.json",
        name: trimmedName.toLowerCase().replace(/_/g, "-"),
        "version-string": "0.1.0",
        dependencies: ["fmt"],
      },
      null,
      2,
    );
  } else if (packageManager === "conan") {
    files["conanfile.txt"] = [
      "[requires]",
      "fmt/10.2.1",
      "",
      "[generators]",
      "CMakeDeps",
      "CMakeToolchain",
      "",
    ].join("\n");
  }

  // 3. Tooling configurations
  if (initClangTools) {
    files[".clang-format"] = generateClangFormat(cppStandard);
    files[".clangd"] = generateClangd(cppStandard);
  }
  files[".gitignore"] = generateGitignore();
  files["README.md"] = generateReadme(trimmedName, buildSystem, cppStandard, testFramework);

  // 4. Source & Header Files
  if (projectType === "cxx-modules") {
    files[`src/${identifier}.mpp`] = [
      "module;",
      "#include <string>",
      `export module ${identifier};`,
      "",
      `export namespace ${identifier} {`,
      "",
      "[[nodiscard]] inline std::string get_greeting() {",
      `    return "Hello from C++${cppStandard} module '${trimmedName}'!";`,
      "}",
      "",
      "[[nodiscard]] constexpr int add(int a, int b) noexcept {",
      "    return a + b;",
      "}",
      "",
      `} // namespace ${identifier}`,
      "",
    ].join("\n");

    files["src/main.cpp"] = [
      "#include <iostream>",
      `import ${identifier};`,
      "",
      "int main() {",
      `    std::cout << ${identifier}::get_greeting() << std::endl;`,
      `    std::cout << "2 + 3 = " << ${identifier}::add(2, 3) << std::endl;`,
      "    return 0;",
      "}",
      "",
    ].join("\n");
  } else if (projectType === "qt") {
    files["src/mainwindow.hpp"] = [
      "#pragma once",
      "",
      "#include <QMainWindow>",
      "",
      "class MainWindow : public QMainWindow {",
      "    Q_OBJECT",
      "",
      "public:",
      "    explicit MainWindow(QWidget *parent = nullptr);",
      "    ~MainWindow() override = default;",
      "};",
      "",
    ].join("\n");

    files["src/mainwindow.cpp"] = [
      '#include "mainwindow.hpp"',
      "#include <QLabel>",
      "",
      "MainWindow::MainWindow(QWidget *parent)",
      "    : QMainWindow(parent) {",
      `    setWindowTitle("${trimmedName}");`,
      "    resize(640, 480);",
      `    setCentralWidget(new QLabel("Welcome to ${trimmedName} (Qt Application)", this));`,
      "}",
      "",
    ].join("\n");

    files["src/main.cpp"] = [
      "#include <QApplication>",
      '#include "mainwindow.hpp"',
      "",
      "int main(int argc, char *argv[]) {",
      "    QApplication app(argc, argv);",
      "    MainWindow window;",
      "    window.show();",
      "    return app.exec();",
      "}",
      "",
    ].join("\n");
  } else if (projectType === "cuda") {
    files[`include/${identifier}/kernel.cuh`] = [
      "#pragma once",
      "",
      `namespace ${identifier} {`,
      "",
      "void run_vector_add(const float *a, const float *b, float *c, int n);",
      "",
      `} // namespace ${identifier}`,
      "",
    ].join("\n");

    files["src/kernel.cu"] = [
      `#include "${identifier}/kernel.cuh"`,
      "#include <cuda_runtime.h>",
      "",
      "__global__ void vector_add_kernel(const float *a, const float *b, float *c, int n) {",
      "    int idx = blockDim.x * blockIdx.x + threadIdx.x;",
      "    if (idx < n) {",
      "        c[idx] = a[idx] + b[idx];",
      "    }",
      "}",
      "",
      `namespace ${identifier} {`,
      "",
      "void run_vector_add(const float *a, const float *b, float *c, int n) {",
      "    float *d_a = nullptr;",
      "    float *d_b = nullptr;",
      "    float *d_c = nullptr;",
      "    size_t size = n * sizeof(float);",
      "    cudaMalloc(&d_a, size);",
      "    cudaMalloc(&d_b, size);",
      "    cudaMalloc(&d_c, size);",
      "",
      "    cudaMemcpy(d_a, a, size, cudaMemcpyHostToDevice);",
      "    cudaMemcpy(d_b, b, size, cudaMemcpyHostToDevice);",
      "",
      "    int threads = 256;",
      "    int blocks = (n + threads - 1) / threads;",
      "    vector_add_kernel<<<blocks, threads>>>(d_a, d_b, d_c, n);",
      "",
      "    cudaMemcpy(c, d_c, size, cudaMemcpyDeviceToHost);",
      "",
      "    cudaFree(d_a);",
      "    cudaFree(d_b);",
      "    cudaFree(d_c);",
      "}",
      "",
      `} // namespace ${identifier}`,
      "",
    ].join("\n");

    files["src/main.cpp"] = [
      `#include "${identifier}/kernel.cuh"`,
      "#include <iostream>",
      "#include <vector>",
      "",
      "int main() {",
      "    constexpr int N = 1024;",
      "    std::vector<float> a(N, 1.0f);",
      "    std::vector<float> b(N, 2.0f);",
      "    std::vector<float> c(N, 0.0f);",
      "",
      `    ${identifier}::run_vector_add(a.data(), b.data(), c.data(), N);`,
      `    std::cout << "CUDA kernel finished. c[0] = " << c[0] << ", c[N-1] = " << c[N - 1] << std::endl;`,
      "    return 0;",
      "}",
      "",
    ].join("\n");
  } else if (projectType === "header-only") {
    files[`include/${identifier}/${identifier}.hpp`] = [
      "#pragma once",
      "",
      "#include <string>",
      "",
      `namespace ${identifier} {`,
      "",
      "[[nodiscard]] inline std::string get_greeting() {",
      `    return "Hello from header-only '${trimmedName}'!";`,
      "}",
      "",
      "[[nodiscard]] constexpr int add(int a, int b) noexcept {",
      "    return a + b;",
      "}",
      "",
      `} // namespace ${identifier}`,
      "",
    ].join("\n");
  } else {
    // executable or library
    files[`include/${identifier}/${identifier}.hpp`] = [
      "#pragma once",
      "",
      "#include <string>",
      "",
      `namespace ${identifier} {`,
      "",
      "[[nodiscard]] std::string get_greeting();",
      "[[nodiscard]] int add(int a, int b) noexcept;",
      "",
      `} // namespace ${identifier}`,
      "",
    ].join("\n");

    files[`src/${identifier}.cpp`] = [
      `#include "${identifier}/${identifier}.hpp"`,
      "",
      `namespace ${identifier} {`,
      "",
      "std::string get_greeting() {",
      `    return "Hello from '${trimmedName}'!";`,
      "}",
      "",
      "int add(int a, int b) noexcept {",
      "    return a + b;",
      "}",
      "",
      `} // namespace ${identifier}`,
      "",
    ].join("\n");

    if (projectType === "executable") {
      files["src/main.cpp"] = [
        `#include "${identifier}/${identifier}.hpp"`,
        "#include <iostream>",
        "",
        "int main() {",
        `    std::cout << ${identifier}::get_greeting() << std::endl;`,
        `    std::cout << "2 + 3 = " << ${identifier}::add(2, 3) << std::endl;`,
        "    return 0;",
        "}",
        "",
      ].join("\n");
    }
  }

  // 5. Test Files
  if (testFramework !== "none") {
    const isModules = projectType === "cxx-modules";
    const headerInclude = isModules
      ? `import ${identifier};`
      : `#include "${identifier}/${identifier}.hpp"`;

    if (testFramework === "catch2") {
      files["tests/test_main.cpp"] = [
        "#include <catch2/catch_test_macros.hpp>",
        headerInclude,
        "",
        'TEST_CASE("Greeting function returns expected message", "[greeting]") {',
        `    REQUIRE(${identifier}::get_greeting().find("${trimmedName}") != std::string::npos);`,
        "}",
        "",
        'TEST_CASE("Add function calculates sum correctly", "[math]") {',
        `    REQUIRE(${identifier}::add(2, 3) == 5);`,
        `    REQUIRE(${identifier}::add(-1, 1) == 0);`,
        "}",
        "",
      ].join("\n");
    } else if (testFramework === "gtest") {
      files["tests/test_main.cpp"] = [
        "#include <gtest/gtest.h>",
        headerInclude,
        "",
        "TEST(ProjectTest, Greeting) {",
        `    EXPECT_NE(${identifier}::get_greeting().find("${trimmedName}"), std::string::npos);`,
        "}",
        "",
        "TEST(ProjectTest, Add) {",
        `    EXPECT_EQ(${identifier}::add(2, 3), 5);`,
        `    EXPECT_EQ(${identifier}::add(-1, 1), 0);`,
        "}",
        "",
      ].join("\n");
    } else if (testFramework === "doctest") {
      files["tests/test_main.cpp"] = [
        "#define DOCTEST_CONFIG_IMPLEMENT_WITH_MAIN",
        "#include <doctest/doctest.h>",
        headerInclude,
        "",
        'TEST_CASE("Testing greeting function") {',
        `    CHECK(${identifier}::get_greeting().find("${trimmedName}") != std::string::npos);`,
        "}",
        "",
        'TEST_CASE("Testing math add") {',
        `    CHECK(${identifier}::add(2, 3) == 5);`,
        `    CHECK(${identifier}::add(-1, 1) == 0);`,
        "}",
        "",
      ].join("\n");
    }
  }

  // 6. Write files to disk if not dryRun
  const filePaths = Object.keys(files);
  if (!dryRun) {
    await fs.mkdir(targetDir, { recursive: true });

    for (const relPath of filePaths) {
      const fullPath = path.join(targetDir, relPath);
      await fs.mkdir(path.dirname(fullPath), { recursive: true });
      await fs.writeFile(fullPath, files[relPath] ?? "", "utf-8");
    }
  }

  // 7. Optional Git init
  let gitInitialized = false;
  if (!dryRun && initGit) {
    const hasGit = await isExecutableAvailable("git");
    if (hasGit) {
      try {
        await execFileAsync("git", ["init"], { cwd: targetDir });
        gitInitialized = true;
      } catch {
        gitInitialized = false;
      }
    }
  }

  // 8. Next steps recommendations
  const nextSteps: string[] = [`cd ${path.relative(process.cwd(), targetDir) || "."}`];
  if (buildSystem === "xmake") {
    nextSteps.push("xmake");
    if (projectType === "executable" || projectType === "cxx-modules" || projectType === "cuda") {
      nextSteps.push("xmake run");
    }
    if (testFramework !== "none") {
      nextSteps.push("xmake test");
    }
    nextSteps.push("xmake project -k compile_commands");
  } else {
    nextSteps.push("cmake -B build -DCMAKE_EXPORT_COMPILE_COMMANDS=ON");
    nextSteps.push("cmake --build build");
    if (testFramework !== "none") {
      nextSteps.push("ctest --test-dir build --output-on-failure");
    }
  }

  return {
    success: true,
    projectName: trimmedName,
    projectDir: targetDir,
    buildSystem,
    projectType,
    cppStandard,
    testFramework,
    packageManager,
    filesCreated: filePaths,
    files,
    nextSteps,
    gitInitialized: initGit ? gitInitialized : undefined,
    message: dryRun
      ? `Dry-run preview for C++ project '${trimmedName}' with ${filePaths.length} file(s).`
      : `Successfully scaffolded C++ project '${trimmedName}' at '${targetDir}'.`,
  };
}
