function sanitizeIdentifier(name: string): string {
  const sanitized = name.replace(/[^a-zA-Z0-9_]/g, "_");
  if (/^[0-9]/.test(sanitized) || CPP_RESERVED_KEYWORDS.has(sanitized.toLowerCase())) {
    return `_${sanitized}`;
  }
  return sanitized;
}

function generateXmakeConfig(
  projectName: string,
  identifier: string,
  projectType: ProjectType,
  cppStandard: CppStandard,
  testFramework: TestFramework,
  packageManager: PackageManager,
): string {
  const lines: string[] = [
    `-- xmake.lua for ${projectName}`,
    "-- Generated by cpp-mcp scaffold",
    'add_rules("mode.debug", "mode.release")',
    "",
    `set_languages("c++${cppStandard}")`,
    'set_warnings("all", "extra")',
    "",
  ];

  if (testFramework === "catch2") {
    lines.push('add_requires("catch2 3.x")');
  } else if (testFramework === "gtest") {
    lines.push('add_requires("gtest")');
  } else if (testFramework === "doctest") {
    lines.push('add_requires("doctest")');
  }

  if (packageManager === "vcpkg") {
    lines.push('-- Note: Add vcpkg dependencies using add_requires("vcpkg::<package>")');
  } else if (packageManager === "conan") {
    lines.push('-- Note: Add conan dependencies using add_requires("conan::<package>")');
  }

  lines.push("");

  switch (projectType) {
    case "executable":
      lines.push(
        `target("${projectName}")`,
        '    set_kind("binary")',
        '    add_files("src/*.cpp")',
        '    add_includedirs("include")',
      );
      break;
    case "library":
      lines.push(
        `target("${projectName}")`,
        '    set_kind("static")',
        '    add_files("src/*.cpp")',
        '    add_includedirs("include", {public = true})',
        `    add_headerfiles("include/(${identifier}/*.hpp)")`,
      );
      break;
    case "header-only":
      lines.push(
        `target("${projectName}")`,
        '    set_kind("headeronly")',
        '    add_includedirs("include", {public = true})',
        `    add_headerfiles("include/(${identifier}/*.hpp)")`,
      );
      break;
    case "cxx-modules":
      lines.push(
        `target("${projectName}")`,
        '    set_kind("binary")',
        '    add_files("src/*.mpp", "src/*.cpp")',
        '    add_includedirs("include")',
      );
      break;
    case "qt":
      lines.push(
        `target("${projectName}")`,
        '    add_rules("qt.widgetapp")',
        '    add_files("src/*.cpp")',
        '    add_frameworks("QtWidgets")',
      );
      break;
    case "cuda":
      lines.push(
        `target("${projectName}")`,
        '    add_rules("cuda")',
        '    add_files("src/*.cu", "src/*.cpp")',
        '    add_includedirs("include")',
      );
      break;
  }

  if (testFramework !== "none") {
    lines.push("");
    lines.push(`target("${projectName}_tests")`);
    lines.push('    set_kind("binary")');
    lines.push("    set_default(false)");
    lines.push('    add_files("tests/*.cpp")');

    if (projectType === "executable") {
      lines.push(`    add_files("src/${identifier}.cpp")`);
      lines.push('    add_includedirs("include")');
    } else if (projectType === "cxx-modules") {
      lines.push('    add_files("src/*.mpp")');
      lines.push('    add_includedirs("include")');
    } else if (projectType === "library" || projectType === "header-only") {
      lines.push(`    add_deps("${projectName}")`);
    } else {
      lines.push('    add_includedirs("include")');
    }

    const pkgName =
      testFramework === "catch2" ? "catch2" : testFramework === "gtest" ? "gtest" : "doctest";
    lines.push(`    add_packages("${pkgName}")`);
    lines.push('    add_tests("default")');
  }

  lines.push("");
  return lines.join("\n");
}

function generateCMakeConfig(
  projectName: string,
  identifier: string,
  projectType: ProjectType,
  cppStandard: CppStandard,
  testFramework: TestFramework,
  packageManager: PackageManager,
): string {
  const minCMakeVer = projectType === "cxx-modules" ? "3.28" : "3.25";
  const lines: string[] = [
    "# CMakeLists.txt",
    "# Generated by cpp-mcp scaffold",
    `cmake_minimum_required(VERSION ${minCMakeVer})`,
    `project(${projectName} VERSION 0.1.0 LANGUAGES CXX${projectType === "cuda" ? " CUDA" : ""})`,
    "",
    `set(CMAKE_CXX_STANDARD ${cppStandard})`,
    "set(CMAKE_CXX_STANDARD_REQUIRED ON)",
    "set(CMAKE_CXX_EXTENSIONS OFF)",
    "set(CMAKE_EXPORT_COMPILE_COMMANDS ON)",
    "",
    "if(MSVC)",
    "    add_compile_options(/W4 /permissive-)",
    "else()",
    "    add_compile_options(-Wall -Wextra -Wpedantic)",
    "endif()",
    "",
  ];

  if (packageManager === "vcpkg") {
    lines.push(
      "# Note: Run cmake with -DCMAKE_TOOLCHAIN_FILE=[vcpkg-root]/scripts/buildsystems/vcpkg.cmake",
    );
    lines.push("");
  }

  switch (projectType) {
    case "executable":
      lines.push(
        `add_executable(${projectName}`,
        "    src/main.cpp",
        `    src/${identifier}.cpp`,
        ")",
        `target_include_directories(${projectName} PRIVATE include)`,
      );
      break;
    case "library":
      lines.push(
        `add_library(${projectName} STATIC`,
        `    src/${identifier}.cpp`,
        ")",
        `target_include_directories(${projectName} PUBLIC`,
        // biome-ignore lint/suspicious/noTemplateCurlyInString: CMake generator expression syntax
        "    $<BUILD_INTERFACE:${CMAKE_CURRENT_SOURCE_DIR}/include>",
        "    $<INSTALL_INTERFACE:include>",
        ")",
      );
      break;
    case "header-only":
      lines.push(
        `add_library(${projectName} INTERFACE)`,
        `target_include_directories(${projectName} INTERFACE`,
        // biome-ignore lint/suspicious/noTemplateCurlyInString: CMake generator expression syntax
        "    $<BUILD_INTERFACE:${CMAKE_CURRENT_SOURCE_DIR}/include>",
        "    $<INSTALL_INTERFACE:include>",
        ")",
      );
      break;
    case "cxx-modules":
      lines.push(
        `add_executable(${projectName}`,
        "    src/main.cpp",
        ")",
        `target_sources(${projectName}`,
        "    PUBLIC",
        "        FILE_SET CXX_MODULES FILES",
        `        src/${identifier}.mpp`,
        ")",
      );
      break;
    case "qt":
      lines.push(
        "find_package(Qt6 REQUIRED COMPONENTS Widgets)",
        "qt_standard_project_setup()",
        `qt_add_executable(${projectName}`,
        "    src/main.cpp",
        "    src/mainwindow.cpp",
        "    src/mainwindow.hpp",
        ")",
        `target_link_libraries(${projectName} PRIVATE Qt6::Widgets)`,
      );
      break;
    case "cuda":
      lines.push(
        `add_executable(${projectName}`,
        "    src/main.cpp",
        "    src/kernel.cu",
        ")",
        `target_include_directories(${projectName} PRIVATE include)`,
        `set_target_properties(${projectName} PROPERTIES CUDA_SEPARABLE_COMPILATION ON)`,
      );
      break;
  }

  if (testFramework !== "none") {
    lines.push("");
    lines.push("enable_testing()");
    lines.push("include(FetchContent)");

    if (testFramework === "catch2") {
      lines.push(
        "FetchContent_Declare(",
        "    Catch2",
        "    GIT_REPOSITORY https://github.com/catchorg/Catch2.git",
        "    GIT_TAG v3.5.3",
        ")",
        "FetchContent_MakeAvailable(Catch2)",
        "",
        `add_executable(${projectName}_tests tests/test_main.cpp)`,
      );
      if (projectType === "executable") {
        lines.push(
          `target_sources(${projectName}_tests PRIVATE src/${identifier}.cpp)`,
          `target_include_directories(${projectName}_tests PRIVATE include)`,
        );
      } else if (projectType === "library" || projectType === "header-only") {
        lines.push(`target_link_libraries(${projectName}_tests PRIVATE ${projectName})`);
      }
      lines.push(
        `target_link_libraries(${projectName}_tests PRIVATE Catch2::Catch2WithMain)`,
        "include(CTest)",
        "include(Catch)",
        `catch_discover_tests(${projectName}_tests)`,
      );
    } else if (testFramework === "gtest") {
      lines.push(
        "FetchContent_Declare(",
        "    googletest",
        "    GIT_REPOSITORY https://github.com/google/googletest.git",
        "    GIT_TAG v1.14.0",
        ")",
        "FetchContent_MakeAvailable(googletest)",
        "",
        `add_executable(${projectName}_tests tests/test_main.cpp)`,
      );
      if (projectType === "executable") {
        lines.push(
          `target_sources(${projectName}_tests PRIVATE src/${identifier}.cpp)`,
          `target_include_directories(${projectName}_tests PRIVATE include)`,
        );
      } else if (projectType === "library" || projectType === "header-only") {
        lines.push(`target_link_libraries(${projectName}_tests PRIVATE ${projectName})`);
      }
      lines.push(
        `target_link_libraries(${projectName}_tests PRIVATE GTest::gtest_main)`,
        "include(GoogleTest)",
        `gtest_discover_tests(${projectName}_tests)`,
      );
    } else if (testFramework === "doctest") {
      lines.push(
        "FetchContent_Declare(",
        "    doctest",
        "    GIT_REPOSITORY https://github.com/doctest/doctest.git",
        "    GIT_TAG v2.4.11",
        ")",
        "FetchContent_MakeAvailable(doctest)",
        "",
        `add_executable(${projectName}_tests tests/test_main.cpp)`,
      );
      if (projectType === "executable") {
        lines.push(
          `target_sources(${projectName}_tests PRIVATE src/${identifier}.cpp)`,
          `target_include_directories(${projectName}_tests PRIVATE include)`,
        );
      } else if (projectType === "library" || projectType === "header-only") {
        lines.push(`target_link_libraries(${projectName}_tests PRIVATE ${projectName})`);
      }
      lines.push(
        `target_link_libraries(${projectName}_tests PRIVATE doctest::doctest)`,
        `add_test(NAME ${projectName}_tests COMMAND ${projectName}_tests)`,
      );
    }
  }

  lines.push("");
  return lines.join("\n");
}

function generateClangFormat(cppStandard: CppStandard): string {
  return [
    "# .clang-format",
    `# Google style preset configured for C++${cppStandard}`,
    "BasedOnStyle: Google",
    "Language: Cpp",
    `Standard: c++${cppStandard}`,
    "ColumnLimit: 100",
    "IndentWidth: 4",
    "TabWidth: 4",
    "UseTab: Never",
    "AccessModifierOffset: -4",
    "SortIncludes: CaseSensitive",
    "",
  ].join("\n");
}

function generateClangd(cppStandard: CppStandard): string {
  return [
    "# .clangd",
    "# Modern clangd configuration for intelligent LSP diagnostics and indexing",
    "CompileFlags:",
    "  Add:",
    `    - -std=c++${cppStandard}`,
    "    - -Wall",
    "    - -Wextra",
    "    - -Wpedantic",
    "    - -Iinclude",
    '  CompilationDatabase: "."',
    "",
    "Diagnostics:",
    "  UnusedIncludes: Strict",
    "  ClangTidy:",
    "    Add:",
    "      - modernize*",
    "      - bugprone*",
    "      - performance*",
    "      - readability*",
    "      - cert*",
    "    Remove:",
    "      - modernize-use-trailing-return-type",
    "",
    "Index:",
    "  Background: Build",
    "",
  ].join("\n");
}

