// Quick index maps
export const SYMBOL_MAP = new Map<string, HeaderEntry>();
export const HEADER_MAP = new Map<string, HeaderEntry>();

for (const entry of CPP_STANDARD_HEADERS) {
  // Normalize header keys: "<vector>", "vector", "<stdio.h>", "stdio.h"
  const cleanHeader = entry.header.replace(/[<>]/g, "").trim().toLowerCase();
  HEADER_MAP.set(cleanHeader, entry);
  HEADER_MAP.set(entry.header.toLowerCase(), entry);

  if (entry.cEquivalent) {
    const cleanC = entry.cEquivalent.replace(/[<>]/g, "").trim().toLowerCase();
    HEADER_MAP.set(cleanC, entry);
    HEADER_MAP.set(entry.cEquivalent.toLowerCase(), entry);
  }

  for (const sym of entry.symbols) {
    SYMBOL_MAP.set(sym, entry);
    // Also index without std:: prefix for convenient fuzzy resolution
    if (sym.startsWith("std::")) {
      const bare = sym.replace(/^std::/, "");
      if (!SYMBOL_MAP.has(bare)) {
        SYMBOL_MAP.set(bare, entry);
      }
    }
  }
}
